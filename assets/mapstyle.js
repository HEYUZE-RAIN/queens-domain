/* 用中点做二次贝塞尔圆滑（比之前 uniform Catmull-Rom 更自然） */
function smooth(pts, close){
  const n = pts.length;
  let d = `M${pts[0][0]},${pts[0][1]}`;
  for(let i = 0; i < n - 1; i++){
    const p = pts[i], q = pts[i + 1];
    const mx = (p[0] + q[0]) / 2, my = (p[1] + q[1]) / 2;
    d += `Q${p[0]},${p[1]} ${mx},${my}`;
  }
  if(close !== false){
    const p = pts[n - 1], q = pts[0];
    d += `Q${p[0]},${p[1]} ${(p[0] + q[0]) / 2},${(p[1] + q[1]) / 2}`;
    d += `Q${q[0]},${q[1]} ${pts[0][0]},${pts[0][1]}Z`;
  }
  return d;
}

function scalePts(pts, k, cx, cy){
  return pts.map(p => [cx + (p[0] - cx) * k, cy + (p[1] - cy) * k]);
}

/* 生成完整底图 */
function buildBaseMap(){
  let o = '';
  // 海面
  o += `<rect width="2000" height="1400" fill="url(#seaAll)"/>`;
  // 极淡的网格（坐标感，不抢戏）
  o += `<rect width="2000" height="1400" fill="url(#paperGrid)" opacity="0.35"/>`;

  // 等深线（两组，离岸越远越淡）
  const rings = [
    { k:1.20, op:0.10, w:1.0 },
    { k:1.11, op:0.16, w:1.1 },
    { k:1.055, op:0.24, w:1.2 }
  ];
  ISLANDS.forEach(is => {
    const cx = is.p.reduce((s, q) => s + q[0], 0) / is.p.length;
    const cy = is.p.reduce((s, q) => s + q[1], 0) / is.p.length;
    rings.forEach(r => {
      o += `<path d="${smooth(scalePts(is.p, r.k, cx, cy))}" fill="none" stroke="#4b8ba0" stroke-opacity="${r.op}" stroke-width="${r.w}"/>`;
    });
    // 浅滩填充光晕
    o += `<path d="${smooth(scalePts(is.p, 1.09, cx, cy))}" fill="${MCOL[is.k].mid}" opacity="0.22" filter="url(#softBig)"/>`;
  });

  // 岛屿本体
  ISLANDS.forEach((is, i) => {
    const c = MCOL[is.k];
    const path = smooth(is.p);
    const cx = is.p.reduce((s, q) => s + q[0], 0) / is.p.length;
    const cy = is.p.reduce((s, q) => s + q[1], 0) / is.p.length;
    o += `<defs><radialGradient id="ig${i}" cx="42%" cy="34%" r="72%">
      <stop offset="0%" stop-color="${c.top}"/><stop offset="62%" stop-color="${c.mid}"/><stop offset="100%" stop-color="${c.bot}"/>
    </radialGradient></defs>`;
    // 投影
    o += `<path d="${smooth(is.p.map(q => [q[0] + 4, q[1] + 8]))}" fill="#000" opacity="0.42" filter="url(#softMed)"/>`;
    // 主体
    o += `<path d="${path}" fill="url(#ig${i})" stroke="${c.line}" stroke-width="2" stroke-opacity="0.5" stroke-linejoin="round"/>`;
    // 海岸内描边（亮）
    o += `<path d="${smooth(scalePts(is.p, 0.972, cx, cy))}" fill="none" stroke="#ffffff" stroke-opacity="0.07" stroke-width="1.2"/>`;
    // 纹理
    o += texFor(is, path, cx, cy);
  });
  return o;
}

function texFor(is, path, cx, cy){
  const xs = is.p.map(q => q[0]), ys = is.p.map(q => q[1]);
  const w = Math.max(...xs) - Math.min(...xs), h = Math.max(...ys) - Math.min(...ys);
  let s = '';
  if(is.t === 'forest'){
    s += `<path d="${path}" fill="url(#texHatch2)" opacity="0.45"/>`;
    // 树林：成簇的小三角，按网格排布更整齐
    let seed = Math.round(cx * 3 + cy);
    const rnd = () => { seed = (seed * 9301 + 49297) % 233280; return seed / 233280; };
    const rows = Math.max(2, Math.round(h / 46)), cols = Math.max(2, Math.round(w / 46));
    for(let r = 0; r < rows; r++){
      for(let c2 = 0; c2 < cols; c2++){
        if(rnd() > 0.62) continue;
        const x = cx - w / 2 + (c2 + 0.5) * (w / cols) + (rnd() - 0.5) * 16;
        const y = cy - h / 2 + (r + 0.5) * (h / rows) + (rnd() - 0.5) * 14;
        const rr = 5 + rnd() * 3.6;
        s += `<path d="M${x.toFixed(1)} ${(y - rr).toFixed(1)} l ${(rr * .8).toFixed(1)} ${rr.toFixed(1)} l ${(-rr * 1.6).toFixed(1)} 0Z" fill="#1b3023" opacity="0.34"/>`;
      }
    }
  } else if(is.t === 'grid'){
    s += `<path d="${path}" fill="url(#texGrid2)" opacity="0.8"/>`;
  } else if(is.t === 'wave'){
    s += `<path d="${path}" fill="url(#texWave2)" opacity="0.85"/>`;
  } else if(is.t === 'tomb'){
    s += `<path d="${path}" fill="url(#texTomb2)" opacity="0.7"/>`;
  } else if(is.t === 'hatch'){
    s += `<path d="${path}" fill="url(#texHatch2)" opacity="0.5"/>`;
  }
  return s;
}

